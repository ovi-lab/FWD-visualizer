"use client";
import { useEffect, useState, useCallback } from "react";
import { Topic } from "./tofParts";
import { useFilter } from "@/app/contexts/filterContext";
import { useChatAnchor } from "@/app/contexts/chatContext";
import { useSelectedNode } from "@/app/contexts/selectedNodeContext";
import "./tof-styles.css";

export default function TiersOfFriendship() {
  const [rows, setRows] = useState([]);
  const [viewBox, setViewBox] = useState({
    x: 0,
    y: 0,
    width: 800,
    height: 600,
  });
  const { filteredTranscript } = useFilter();
  const { chatAnchor, setChatAnchor } = useChatAnchor();
  const { selectedNode, setSelectedNode } = useSelectedNode();

  const svgMode = false; //For switching to use SVGs

  const handleSlotClick = (clickedID) => {
    setChatAnchor(`response${clickedID}`);
  };

  const handleTopicClick = (nodeName) => {
    setSelectedNode(nodeName);
  };

  useEffect(() => {
    if (!filteredTranscript) return;
    const rows = [[]];
    filteredTranscript.map((line) => {
      const lineSlots = line.slots
        .filter(
          (slot) =>
            !(
              slot.name.includes("error") ||
              slot.name.includes("any") ||
              slot.name.includes("topic_name") ||
              slot.name.includes("agreement_patterns")
            )
        )
        .map((filteredSlot) => ({ slotData: filteredSlot, slotID: line.idx }));
      try {
        const topic_category = line.topic.match(/[A-Za-z]+/)[0];
        if (topic_category.includes(["command", "system", "error"])) return;
      } catch (error) {
        console.log(
          `Error when checking for the topic generated by intent \"${line.topic.intent}\". The topic found was \"${line.topic}\"`
        );
        console.log("error", error);
      }

      const topicNode = { topic: line.topic, required: [], collected: [] };
      let placementIndex = 0;
      let alreadyExists = false;
      for (let i = 0; i < rows.length; i++) {
        for (const existing of rows[i]) {
          if (line.topic === "topic-intro" && lineSlots !== undefined) {
            if (existing.collected.length === 0) existing.collected = lineSlots;

            // TODO: index locations
          }

          if (existing.topic === topicNode.topic) {
            topicNode.collected.forEach((objectSlot) => {
              const exists = existing.collected.some(
                (existingSlot) =>
                  existingSlot.slotData.name === objectSlot.slotData.name
              );
              if (!exists) {
                existing.collected.push(objectSlot);
              }
            });
            alreadyExists = true;
            break;
          }

          for (const slot of lineSlots) {
            if (
              existing.collected.find((collected) =>
                collected.slotData.name.includes(slot.slotData.name)
              )
            ) {
              topicNode.required.push(slot);
              placementIndex = i + 1;
            }
          }
        }

        if (alreadyExists) break;
        topicNode.collected = lineSlots.filter(
          (lineSlot) => !topicNode.required.includes(lineSlot)
        );
      }

      if (!alreadyExists)
        placementIndex > rows.length - 1
          ? rows.push([topicNode])
          : rows[placementIndex].push(topicNode);
    });
    setRows(rows);
  }, [filteredTranscript]);

  useEffect(() => {
    // Calculate bounding box of the generated content
    if (!filteredTranscript) return;
    const svgContent = document.getElementById("tof-content");
    if (svgContent) {
      const { newX, newY, newWidth, newHeight } = svgContent.getBBox();
      const newViewBox = {
        x: newX,
        y: newY,
        width: newWidth,
        height: newHeight,
      };
      setViewBox(newViewBox);
    }
  }, [filteredTranscript]);

  if (!filteredTranscript || !rows)
    return <div className="flex flex-col h-full">Loading...</div>;

  if (!svgMode) {
    return (
      <div className={`grid grid-rows-${rows.length} overflow-auto`}>
        {rows.map((row) => {
          // Only render the row if it has nodes
          console.log("row", row);
          return (
            row !== undefined && (
              <div
                key={`${row.topic}`}
                className="flex justify-center topic-wrapper"
              >
                {row.map((node) => {
                  console.log(`node-${node.topic}-${node.collected.length}-${node.required.length}`)
                  return (
                    <Topic
                      key={`node-${node.topic}-${node.collected.length}-${node.required.length}`}
                      nodeTopic={node.topic}
                      nodeCollected={node.collected}
                      nodeRequired={node.required}
                      handleTopicClick={handleTopicClick}
                      handleSlotClick={handleSlotClick}
                    />
                  );
                })}
              </div>
            )
          );
        })}
      </div>
    );
  }
}
